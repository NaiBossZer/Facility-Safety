import { chromium } from 'playwright';
import { buildDefaultCatalog } from './src/config/seed/defaultCatalog.js';
const browser = await chromium.launch({ headless: true, executablePath: 'C:\\Program Files\\Google\\Chrome\\Application\\chrome.exe' });
const page = await browser.newPage({ viewport: { width: 1440, height: 900 } });
const catalog = buildDefaultCatalog();
await page.addInitScript((c) => localStorage.setItem('fsa:v2:catalog', JSON.stringify(c)), catalog);
const logs = [];
page.on('console', m => { if (m.type() === 'error' || m.type() === 'warning') logs.push(`${m.type()}: ${m.text()}`); });
page.on('pageerror', e => logs.push(`pageerror: ${e.message}`));
await page.goto('http://127.0.0.1:4178/', { waitUntil: 'networkidle' });
await page.locator('select').selectOption({ index: 1 });
await page.locator('input').first().fill('1234');
await page.getByRole('button', { name: 'เข้าสู่ระบบ' }).click();
await page.getByRole('button', { name: /Inspection Checklist/ }).click();
await page.waitForTimeout(900);
const selects = await page.locator('select').count();
const before = (await page.locator('main').first().innerText()).slice(0, 1800);
if (selects >= 2) await page.locator('select').nth(0).selectOption({ index: 1 });
if (selects >= 2) await page.locator('select').nth(1).selectOption({ index: 1 });
await page.waitForTimeout(500);
const failButtons = page.getByRole('button', { name: 'ไม่ผ่าน' });
if (await failButtons.count()) await failButtons.first().click();
const note = page.locator('textarea').first();
if (await note.count()) await note.fill('TEST inspection flow');
await page.getByRole('button', { name: /บันทึกผลการตรวจสอบ/ }).click();
await page.waitForTimeout(1200);
const after = await page.locator('main').first().innerText();
await page.getByRole('button', { name: /Work Orders/ }).click();
await page.waitForTimeout(700);
const wo = await page.locator('main').first().innerText();
console.log(JSON.stringify({ selects, before, inspectionSaved: after.includes('บันทึกผลการตรวจสอบ'), workOrderCreated: !wo.includes('ทั้งหมด 0 รายการ'), workOrderText: wo.slice(0,1200), logs }, null, 2));
await browser.close();